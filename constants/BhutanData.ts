/**
 * Resolves precise coordinates for a given Bhutanese zone and region.
 *
 * @param zone Sub-zone or neighborhood string
 * @param region Municipal district (Thimphu, Phuentsholing, Paro, etc.)
 * @returns Object with latitude and longitude numbers
 */
export function getZoneCoordinates(zone: string = '', region: string = ''): { latitude: number; longitude: number } {
  const cleanZone = (zone || '').trim().toLowerCase();
  for (const [key, coords] of Object.entries(BHUTAN_ZONE_COORDINATES)) {
    if (cleanZone.includes(key.toLowerCase()) || key.toLowerCase().includes(cleanZone)) {
      return coords;
    }
  }

  // District core fallbacks
  if (region === 'Thimphu') return { latitude: 27.4728, longitude: 89.6393 };
  if (region === 'Phuentsholing') return { latitude: 26.8640, longitude: 89.3884 };
  if (region === 'Paro') return { latitude: 27.4287, longitude: 89.4164 };
  if (region === 'Punakha') return { latitude: 27.5810, longitude: 89.8630 };

  return { latitude: 27.4728, longitude: 89.6393 };
}

